// On-screen text with GTA's font 4. kRight ends at `edge`; kWrap wraps at `edge`.
enum class Align { Left, Centre, Right, Wrap };
inline void Text(const char* s, float x, float y, float scale, int r, int g, int b, int a = 255,
                 Align align = Align::Left, float edge = 0.0f, bool outline = true) {
    Call<void>(SET_TEXT_FONT, 4);
    Call<void>(SET_TEXT_SCALE, scale, scale);
    Call<void>(SET_TEXT_COLOUR, r, g, b, a);
    if (outline) Call<void>(SET_TEXT_OUTLINE);
    if (align == Align::Centre) Call<void>(SET_TEXT_CENTRE, 1);
    if (align == Align::Right) {
        Call<void>(SET_TEXT_WRAP, 0.0f, edge);
        Call<void>(SET_TEXT_RIGHT_JUSTIFY, 1);
    } else if (align == Align::Wrap) {
        Call<void>(SET_TEXT_WRAP, x, edge);
    }
    Call<void>(BEGIN_TEXT_COMMAND_DISPLAY_TEXT, "STRING");
    Call<void>(ADD_TEXT_COMPONENT_SUBSTRING_PLAYER_NAME, s);
    Call<void>(END_TEXT_COMMAND_DISPLAY_TEXT, x, y, 0);
}

// A GTA full-screen frontend is up (pause menu in any state, a warning
// screen such as quit game, a loading screen): SkateV's overlays stay off.
inline bool FrontendActive() {
    return Call<BOOL>(IS_PAUSE_MENU_ACTIVE) || Call<int>(GET_PAUSE_MENU_STATE) != 0 ||
           Call<BOOL>(IS_WARNING_MESSAGE_ACTIVE) || Call<BOOL>(GET_IS_LOADING_SCREEN_ACTIVE);
}

